/** مجموعة رسائل بنبرتين: فصحى صارمة ومصري ساخر. كل العبارات أصلية. */
class Msg(val strict: List<String>, val egy: List<String>) {
    fun forMode(m: Mode): List<String> = when (m) {
        Mode.STRICT -> strict
        Mode.EGYPTIAN -> egy
        Mode.MIXED -> strict + egy
    }
}

fun String.fill(vararg kv: Pair<String, Any>): String {
    var s = this
    kv.forEach { s = s.replace("{" + it.first + "}", it.second.toString()) }
    return s
}

/** اختيار عشوائي لا يكرر آخر عدة رسائل من المفتاح نفسه. */
class MessagePicker(context: Context) {
    private val p = context.getSharedPreferences("enjaz_msgs", Context.MODE_PRIVATE)

    fun pick(key: String, list: List<String>): String {
        if (list.isEmpty()) return ""
        if (list.size == 1) return list[0]
        val recent = (p.getString(key, "") ?: "").split(",").mapNotNull { it.toIntOrNull() }
        val avoid = recent.take(minOf(list.size - 1, 4))
        val idx = list.indices.filter { it !in avoid }.random()
        p.edit().putString(key, (listOf(idx) + recent).take(6).joinToString(",")).apply()
        return list[idx]
    }
}

